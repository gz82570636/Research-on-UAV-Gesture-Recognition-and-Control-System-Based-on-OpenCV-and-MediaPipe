#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
================================================================================
香橙派端配置文件 - 无人机手势控制系统
================================================================================

功能说明:
    本文件包含香橙派端的所有配置参数，包括:
    1. 摄像头配置 - 香橙派使用 /dev/video3
    2. MediaPipe 手部检测参数
    3. 手势控制参数 - 手势保持阈值、位置步长
    4. 手势到位置增量的映射表

使用注意:
    - 香橙派USB摄像头通常在 /dev/video3
    - 如果使用CSI摄像头，可能需要在 /dev/video0
    - 可以通过命令 `ls /dev/video*` 查看可用设备
    - 方向定义基于无人机机体坐标系（NED坐标系）:
      * x轴: 前进(+) / 后退(-)
      * y轴: 左移(+) / 右移(-)
      * z轴: 上升(+) / 下降(-)

网络配置:
    ROS_MASTER_URI = http://192.168.1.11:11311 (虚拟机IP)
    ROS_IP = 192.168.1.12 (香橙派IP)
================================================================================
"""

# ==============================================================================
# 第一部分: 硬件配置
# ==============================================================================

# 摄像头设备节点路径
# 香橙派3B的USB摄像头通常在 /dev/video3
# CSI摄像头通常在 /dev/video0
# 使用整数0表示第一个设备，字符串"/dev/video3"表示具体设备
VIDEO_DEVICE = "/dev/video1"

# 目标帧率 (FPS: Frames Per Second)
# 15fps是平衡选择，既保证响应速度又不过度占用CPU
TARGET_FPS = 15

# 图像分辨率
# 640x480是标准分辨率，兼容性好，计算量适中
FRAME_WIDTH = 640
FRAME_HEIGHT = 480


# ==============================================================================
# 第二部分: MediaPipe 手部检测配置
# ==============================================================================

# MediaPipe Hands 初始化参数
MEDIAPIPE_CONFIG = {
    "static_image_mode": False,
    "max_num_hands": 1,
    "min_detection_confidence": 0.7,
    "min_tracking_confidence": 0.5,
}


# ==============================================================================
# 第三部分: 算法配置
# ==============================================================================

# 滑动窗口平滑的窗口大小
# 用最近多少帧的均值作为当前估计值
# 5是平衡值：既平滑抖动又不过度延迟（约0.33秒延迟）
SMOOTHING_WINDOW_SIZE = 5


# ==============================================================================
# 第四部分: 手势控制配置
# ==============================================================================

# 手势保持生效阈值(秒)
# 手势必须保持这么长时间才会触发对应的控制指令
# 作用：防止手部轻微晃动导致的误触发
# 0.4秒是平衡值：既响应快又稳定
HOLD_THRESHOLD_SEC = 0.4

# 持续移动的时间间隔(秒)
# 当手势持续指向时，每多少秒移动一步
# 0.3秒表示约每秒移动3步
CONTINUOUS_MOVE_INTERVAL = 0.3

# 位置增量步长(米)
# 每次移动的距离，与drone_control.py的WASD步长一致
POSITION_STEP = 0.5

# 最小和最大高度限制(米)
# 防止无人机飞得太低或太高
MIN_ALTITUDE = 0.5   # 最低0.5米，防止撞地
MAX_ALTITUDE = 5.0   # 最高5米，防止飞丢


# ==============================================================================
# 第五部分: 手势到位置增量的映射表
# ==============================================================================
#
# 核心概念：手势 = 虚拟键盘
# 识别到什么手势，就相当于在虚拟机上按了什么键
#
# 食指向上   → 按了W键 → 无人机向前(target_x += 0.5)
# 食指向下   → 按了S键 → 无人机向后(target_x -= 0.5)
# 食指向左   → 按了A键 → 无人机向左(target_y += 0.5)
# 食指向右   → 按了D键 → 无人机向右(target_y -= 0.5)
# 左手张开   → 按了1键 → 解锁并悬停在2米
# 左手握拳   → 按了3键 → 降落
#
# 坐标系说明（NED坐标系）：
#   dx: x轴增量，+0.5=前进，-0.5=后退
#   dy: y轴增量，+0.5=左移，-0.5=右移
#

GESTURE_TO_KEY = {
    # 右手食指指向 - 相当于WASD按键（只保留4个方向）
    "Pointing Up":         "W",      # 前进
    "Pointing Down":       "S",      # 后退
    "Pointing Left":       "A",      # 左移
    "Pointing Right":      "D",      # 右移
    # 左手手势 - 功能控制
    "Left Open":           "按键1",   # 解锁+悬停
    "Left Fist":           "按键3",   # 降落
    "Left Pointing Up":    "高度+",   # 上升
    "Left Pointing Down":  "高度-",   # 下降
}

# 手势到位置增量的映射字典
# 每个手势对应的位置变化量(dx, dy)
# 与drone_control.py的WASD步长完全一致
GESTURE_STEP = {
    # 右手食指指向 - 只保留4个方向（去掉斜方向，提升识别可靠性）
    "Pointing Up":         {"dx":  0.5, "dy":  0.0},   # 相当于W：前进+0.5m
    "Pointing Down":       {"dx": -0.5, "dy":  0.0},   # 相当于S：后退-0.5m
    "Pointing Left":       {"dx":  0.0, "dy":  0.5},   # 相当于A：左移+0.5m
    "Pointing Right":      {"dx":  0.0, "dy": -0.5},   # 相当于D：右移-0.5m
}

# 高度控制手势映射（左手食指上下）
# dz: z轴增量（高度变化），+0.5=上升，-0.5=下降
ALTITUDE_STEP = {
    "Left Pointing Up":    0.5,   # 上升+0.5m
    "Left Pointing Down":  -0.5,  # 下降-0.5m
}


# ==============================================================================
# 第六部分: ROS网络配置
# ==============================================================================

# 虚拟机ROS Master的IP地址和端口
# 香橙派通过这个地址连接到虚拟机的ROS Master
VM_ROS_MASTER_IP = "192.168.1.11"
VM_ROS_MASTER_PORT = 11311

# 香橙派本机的IP地址
# 告诉ROS其他节点如何连接到香橙派
ORANGEPI_IP = "192.168.1.12"

# 完整的ROS Master URI
ROS_MASTER_URI = f"http://{VM_ROS_MASTER_IP}:{VM_ROS_MASTER_PORT}"


# ==============================================================================
# 第七部分: 手势说明（供参考）
# ==============================================================================
"""
手势识别说明:

右手食指指向（需要食指伸直，其他手指弯曲）:
  - 向上:   食指指向摄像头上方 → 无人机前进
  - 向下:   食指指向摄像头下方 → 无人机后退
  - 向左:   食指指向摄像头左侧 → 无人机左移
  - 向右:   食指指向摄像头右侧 → 无人机右移
  - 斜向:   食指指向斜角方向 → 无人机斜向移动

左手手势（不需要食指伸直，看手指状态）:
  - 张开:   五指都伸直 → 解锁+悬停（如果未解锁）
  - 握拳:   五指都弯曲 → 降落（如果已在飞行）

保持时间:
  - 所有手势都需要保持至少0.4秒才会生效
  - 这是为了防止手部轻微晃动导致的误触发
  - 持续指向时，每0.3秒移动一步
"""